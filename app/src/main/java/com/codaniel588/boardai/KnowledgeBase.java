    public static String answer(String question, String filter) {
        String q = normalize(question);
        if (q.isEmpty()) return "כתוב שאלה ואענה לפי מאגר הידע המקומי.";
        if (isGreeting(q)) return "שלום! אני BoardAI 👋\nאני עובד בלי אינטרנט. שאל על קטאן, מונופול, פוקר, תקלות בבית, מחשבים ועוד.";
        if (q.contains("מי אתה") || q.contains("מה אתה")) return "אני BoardAI — עוזר ידע מקומי בעברית. אין צורך באינטרנט, חשבון או שרת.";
        if (q.contains("מה יש לך") || q.contains("על מה אתה יודע") || q.contains("איזה נושאים")) {
            return "משחקים: קטאן, מונופול ופוקר.\nבית: חשמל, נזילות, סתימות ומכשירי חשמל.\nמחשב: רשת, איטיות, תוכנות, מדפסות וקיצורים.\nיום יום: מידות, אחוזים ופתרון תקלות.";
        }

        List<Entry> ranked = new ArrayList<>();
        for (Entry e : ALL) {
            if (!matchesFilter(e, filter)) continue;
            int score = score(q, e);
            if (score > 0) ranked.add(e);
        }
        ranked.sort((a,b) -> Integer.compare(score(q,b), score(q,a)));

        if (!ranked.isEmpty()) {
            Entry best = ranked.get(0);
            String prefix = best.category.equals("קטאן") || best.category.equals("מונופול") || best.category.equals("פוקר")
                    ? "🎲 " : best.category.equals("בית") ? "🏠 " : best.category.equals("מחשב") ? "💻 " : "💡 ";
            return prefix + best.title + "\n\n" + best.answer;
        }

        return "לא מצאתי התאמה מספיק מדויקת. נסה לציין את המכשיר/המשחק ואת מה שקרה בפועל, למשל: «מחשב — אין אינטרנט» או «קטאן — יצא 7».";
    }

    private static boolean matchesFilter(Entry e, String filter) {
        if (filter.equals("הכול")) return true;
        if (filter.equals("משחקים")) return e.category.equals("קטאן") || e.category.equals("מונופול") || e.category.equals("פוקר") || e.category.equals("כללי");
        return e.category.equals(filter);
    }

    private static int score(String q, Entry e) {
        int s = 0;
        String title = normalize(e.title);
        if (q.equals(title)) s += 20;
        else if (q.contains(title) && title.length() > 3) s += 10;

        for (String key : e.keys) {
            String k = normalize(key);
            if (k.isEmpty()) continue;
            if (q.contains(k)) s += k.length() >= 5 ? 5 : 2;
        }

        String[] words = q.split(" ");
        for (String word : words) {
            if (word.length() < 3) continue;
            if (title.contains(word)) s += 2;
            for (String key : e.keys) if (normalize(key).contains(word)) s += 1;
        }
        return s;
    }

    private static boolean isGreeting(String q) {
        return q.equals("שלום") || q.equals("היי") || q.equals("אהלן") || q.equals("הי") || q.contains("שלום לך");
    }

    private static String normalize(String s) {
        String n = Normalizer.normalize(s == null ? "" : s, Normalizer.Form.NFKC)
                .toLowerCase(Locale.ROOT);
        n = n.replace("־","-").replace("’","'").replace("״",""").replace("״",""");
        n = n.replaceAll("[^\p{L}\p{N} -]", " ");
        n = n.replaceAll("\s+", " ").trim();
        n = n.replace("קטן","קטאן").replace("קטאןן","קטאן").replace("מונפול","מונופול");
        return n;
    }

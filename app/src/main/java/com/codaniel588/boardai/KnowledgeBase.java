    public static String answer(String question, String filter) {
        String q = normalize(question);
        if (q.trim().isEmpty()) return "כתוב שאלה ואענה לפי מאגר המשחקים המקומי.";
        if (q.contains("שלום") || q.contains("היי")) return "שלום! אני BoardAI. שאל אותי כל דבר על קטאן, מונופול או פוקר — גם על מצבי מחלוקת.";
        if (q.contains("מי אתה") || q.contains("מה אתה")) return "אני BoardAI — עוזר משחקים בעברית שעובד בלי אינטרנט, עם מאגר ידע מקומי.";
        if (q.contains("איזה משחקים") || q.contains("מה אתה יודע") || q.contains("על מה")) return "כרגע אני מתמחה בקטאן, מונופול ופוקר (כולל כמה מהווריאציות המרכזיות). הידע נמצא בתוך האפליקציה ולכן אין צורך בחיבור.";

        List<Entry> ranked = new ArrayList<>();
        for (Entry e : ALL) {
            if (!filter.equals("הכול") && !e.game.equals(filter) && !e.game.equals("כללי")) continue;
            int score = score(q, e);
            if (score > 0) ranked.add(e);
        }
        ranked.sort((a,b) -> Integer.compare(score(q,b), score(q,a)));
        if (!ranked.isEmpty()) {
            Entry best = ranked.get(0);
            return "📘 " + best.title + "\n\n" + best.answer;
        }

        String game = detectGame(q);
        if (!game.isEmpty()) {
            return "אני מזהה שמדובר ב" + game + ", אבל לא מצאתי התאמה מספיק מדויקת במאגר המקומי. נסה לנסח למשל: 'מה קורה כאשר...', או ציין את המהדורה.";
        }
        return "לא מצאתי תשובה מדויקת במאגר המקומי. נסה להוסיף את שם המשחק ואת המצב, למשל: 'קטאן — יצא 7', 'מונופול — לא קנו נכס', 'פוקר — אומהה'.";
    }

    private static int score(String q, Entry e) {
        int s = 0;
        if (normalize(e.title).contains(q) && q.length() > 3) s += 8;
        for (String key : e.keys) {
            String k = normalize(key);
            if (q.contains(k)) s += k.length() >= 4 ? 4 : 2;
        }
        if (q.contains(normalize(e.game))) s += 3;
        if (e.game.equals("כללי") && (q.contains("מחלוקת") || q.contains("חוק"))) s += 2;
        return s;
    }

    private static String detectGame(String q) {
        if (q.contains("קטאן") || q.contains("catan")) return "קטאן";
        if (q.contains("מונופול") || q.contains("monopoly")) return "מונופול";
        if (q.contains("פוקר") || q.contains("poker") || q.contains("הולדם") || q.contains("אומהה")) return "פוקר";
        return "";
    }

    private static String normalize(String s) {
        String n = Normalizer.normalize(s == null ? "" : s, Normalizer.Form.NFKC).toLowerCase(Locale.ROOT);
        n = n.replace("־","-").replace("’","'").replaceAll("[^\\p{L}\\p{N} -]", " ");
        n = n.replaceAll("\\s+", " ").trim();
        n = n.replace("קטן","קטאן").replace("קטאןן","קטאן").replace("מונפול","מונופול");
        return n;
    }
